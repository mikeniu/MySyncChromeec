/* Helper macros for bit field access */
#define SGM_FIELD_MASK(_reg, _field) \
    GENMASK((_reg##_##_field##_SHIFT + _reg##_##_field##_BITS - 1), \
            _reg##_##_field##_SHIFT)

#define GET_SGM_FIELD(_reg, _field, _x) \
    (((_x) >> _reg##_##_field##_SHIFT) & \
     GENMASK(_reg##_##_field##_BITS - 1, 0))

#define SET_SGM_FIELD(_reg, _field, _v, _x) \
    (((_x) & ~SGM_FIELD_MASK(_reg, _field)) | \
     (((_v) & GENMASK(_reg##_##_field##_BITS - 1, 0)) \
      << _reg##_##_field##_SHIFT))

