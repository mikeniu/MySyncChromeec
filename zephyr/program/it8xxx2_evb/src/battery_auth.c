#define KEY_SEL_MASK   (BIT(4) | BIT(3))
#define SMBUS_CMD_OP_MFG  0x3e

enum key_type {
	KEY_TI      = 1,
	KEY_RENESAS = 2,
	KEY_MPC     = 3,
};
struct ecc_pubkey {
	const uint8_t *qx;
	const uint8_t *qy;
};

static const struct ecc_pubkey key_table[] = {
	[KEY_RENESAS] = {
		.qx = qx_renesas,
		.qy = qy_renesas,
	},
	[KEY_MPC] = {
		.qx = qx_mpc,
		.qy = qy_mpc,
	},
};

void battery_auth(void)
{
	if (!device_is_ready(i2c_bus.bus)) {
		printk("I2C bus not ready\n");
		return;
	}

	printk("Start battery auth...\n");

	uint8_t data, idx;
	uint8_t cmd = SMBUS_CMD_OP_MFG;

	i2c_write_read(i2c_bus.bus, i2c_bus.addr, &cmd, 1, &data, 1);
	idx = (data & KEY_SEL_MASK) >> 3;

	if (battery_auth_flow(&i2c_bus, random_num, key_table[idx].qx, key_table[idx].qy)) {
		printk("Battery Verify fail\n");
	} else {
		printk("Battery Verify success\n");
	}
}
DECLARE_HOOK(HOOK_INIT, battery_auth, HOOK_PRIO_POST_DEFAULT);
