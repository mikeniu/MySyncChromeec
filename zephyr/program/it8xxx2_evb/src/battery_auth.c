#include "hooks.h"
#include "task.h"
#include "i2c.h"

#include <zephyr/kernel.h>
#include <zephyr/device.h>
#include <zephyr/devicetree.h>
#include <zephyr/drivers/i2c.h>
#include <zephyr/sys/printk.h>

#define BATTERY_NODE DT_NODELABEL(battery)

extern int battery_auth_flow(const struct i2c_dt_spec *i2c, const uint8_t *random_num,
			      const uint8_t *pubkey_qx, const uint8_t *pubkey_qy);

static const struct i2c_dt_spec i2c_bus = I2C_DT_SPEC_GET(BATTERY_NODE);

static uint8_t random_num[32] = {
	0x04, 0x03, 0x02, 0x01, 0x08, 0x07, 0x06, 0x05,
	0x0c, 0x0b, 0x0a, 0x09, 0x10, 0x0f, 0x0e, 0x0d,
	0x04, 0x03, 0x02, 0x01, 0x08, 0x07, 0x06, 0x05,
	0x0c, 0x0b, 0x0a, 0x09, 0x10, 0x0f, 0x0e, 0x0d,
};

const uint8_t qx[32] = {
	0x9e, 0xb6, 0x84, 0x7f,
	0xb3, 0x98, 0xc4, 0x88,
	0x0e, 0x3c, 0x92, 0x1c,
	0xea, 0xe5, 0xc3, 0xbb,
	0xc4, 0x3a, 0x31, 0x2b,
	0x56, 0xd7, 0x6a, 0x4f,
	0x2b, 0x96, 0x96, 0x1f,
	0x13, 0xfa, 0xe2, 0x3a
};
const uint8_t qy[32] = {
	0xc7, 0x46, 0xe3, 0xfa,
	0x88, 0xd5, 0x08, 0xd6,
	0xba, 0x7a, 0x90, 0x95,
	0x4b, 0x3a, 0x2d, 0x8e,
	0x73, 0x04, 0xe3, 0x1e,
	0xd2, 0x93, 0x8d, 0xf3,
	0x6d, 0x81, 0x18, 0x11,
	0x8a, 0x6f, 0xfd, 0xf0
};

void battery_auth(void)
{
	if (!device_is_ready(i2c_bus.bus)) {
		printk("I2C bus not ready\n");
		return;
	}

	printk("Start battery auth...\n");

	if (battery_auth_flow(&i2c_bus, random_num, qx, qy)) {
		printk("Battery Verify fail\n");
	} else {
		printk("Battery Verify success\n");
	}
}
DECLARE_HOOK(HOOK_INIT, battery_auth, HOOK_PRIO_POST_DEFAULT);
