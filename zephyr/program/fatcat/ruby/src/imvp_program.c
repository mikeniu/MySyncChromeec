static int imvp_read_test_run(void)
{
	uint8_t val;
	int rv, rc;

	k_usleep(500);

	/*Check NVM Status*/
	rv = imvp_read(0xEC, &val);
	if (rv)
		return rv;
	if (!(val & BIT(7))) {
		k_msleep(1);
		rv = imvp_read(0xEC, &val);
		if (rv)
			return rv;
		if (!(val & BIT(7))) {
			CPRINTS("IMVP fault 1: EC[7] not set");
			return EC_ERROR_UNKNOWN;
		}
	}

	/*Check Product ID, Config ID, Revision ID*/
	rv = imvp_read(0xFE, &val);
	if (rv)
		return rv;
	if (val != 0x45) {
		CPRINTF("IMVP fault 2: reg 0xFE = 0x%x (expected 0x45)\n", val);
		return EC_ERROR_UNKNOWN;
	}
	rv = imvp_read(0xFA, &val);
	if (rv)
		return rv;
	if (val != 0x00) {
		CPRINTF("IMVP fault 2: reg 0xFA = 0x%x (expected 0x00)\n", val);
		return EC_ERROR_UNKNOWN;
	}
	rv = imvp_read(0xE0, &val);
	if (rv)
		return rv;
	if (val != 0x01) {
		CPRINTF("IMVP fault 2: reg 0xE0 = 0x%x (expected 0x01)\n", val);
		return EC_ERROR_UNKNOWN;
	}

	/*Check FW version*/
	imvp_write(0xEF, 0x08);
	rv = imvp_read(0x09, &val);
	if (rv)
		return rv;
	if (val != 0x07) {
		CPRINTF("IMVP FW version error: reg 0x09 = 0x%x (expected 0x07)\n",
			val);
		rc = imvp_write_data();
		if (rc)
			return rc;
		rc = imvp_write_data_2();
		if (rc)
			return rc;
	}

	/*Check CRC*/
	imvp_write(0xEF, 0x02);
	rv = imvp_read(0x17, &val);
	if (rv)
		return rv;
	if (val != 0xB9) {
		CPRINTF("IMVP CRC0 error: reg 0x17 = 0x%x (expected 0xB9)\n",
			val);
		rc = imvp_write_data();
		if (rc)
			return rc;
		rc = imvp_write_data_2();
		if (rc)
			return rc;
	}
	imvp_write(0xEF, 0x08);
	rv = imvp_read(0x0A, &val);
	if (rv)
		return rv;
	if (val != 0x82) {
		CPRINTF("IMVP CRC1 error: reg 0x0A = 0x%x (expected 0x82)\n",
			val);
		rc = imvp_write_data();
		if (rc)
			return rc;
		rc = imvp_write_data_2();
		if (rc)
			return rc;
	}
	imvp_write(0xEF, 0x0E);
	rv = imvp_read(0x0F, &val);
	if (rv)
		return rv;
	if (val != 0xBB) {
		CPRINTF("IMVP CRC2 error: reg 0x0F = 0x%x (expected 0xBB)\n",
			val);
		rc = imvp_write_data();
		if (rc)
			return rc;
		rc = imvp_write_data_2();
		if (rc)
			return rc;
	}
	CPRINTF("Programming Done!");
	return EC_SUCCESS;
}

