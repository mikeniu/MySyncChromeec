static int imvp_write_data(void)
{
	uint8_t val;
	int rv, i, retry;

	/*Unlock NVM*/
	imvp_write(0xF1, 0x24);
	imvp_write(0xF1, 0x54);
	imvp_write(0xF1, 0x02);

	/*Write Data*/
	for (i = 0; i < ARRAY_SIZE(imvp_fw_write_data); i++)
		imvp_write(imvp_fw_write_data[i].reg,
			   imvp_fw_write_data[i].data);

	/*Store NVM*/
	imvp_write(0xED, 0xAA);
	k_msleep(850);

	/*Check NVM Status*/
	for (retry = 0; retry < 20; retry++) {
		rv = imvp_read(0xEC, &val);
		if (rv)
			return rv;

		if (val & BIT(6))
			break;
		k_msleep(1);
	}
	if (!(val & BIT(6))) {
		CPRINTS("IMVP fault 3: EC[6] not set after 20 retries");
		return EC_ERROR_UNKNOWN;
	}

	/*Restore NVM*/
	imvp_write(0xED, 0x66);
	k_usleep(500);

	/*Check NVM Status*/
	rv = imvp_read(0xEC, &val);
	if (rv)
		return rv;
	if (val != 0xE0) {
		k_msleep(1);
		rv = imvp_read(0xEC, &val);
		if (rv)
			return rv;
		if (val != 0xE0) {
			CPRINTS("IMVP fault 4: reg 0xEC != 0xE0");
			return EC_ERROR_UNKNOWN;
		}
	}
	return EC_SUCCESS;
}
static int imvp_write_data_2(void)
{
	uint8_t val;
	int i, rc, rv, retry;

	/*Check FW version*/
	for (retry = 0; retry < 4; retry++) {
		rv = imvp_read(0x09, &val);
		if (rv)
			return rv;

		if (val == 0x07)
			break;
		rc = imvp_write_data();
		if (rc)
			return rc;
	}
	if (val != 0x07) {
		CPRINTS("IMVP fault 5: FW version not set after 4 retries");
		return EC_ERROR_UNKNOWN;
	}

	/*Check FW version*/
	for (retry = 0; retry < 4; retry++) {
		imvp_write(0xEF, 0x02);
		rv = imvp_read(0x17, &val);
		if (rv)
			return rv;

		if (val == 0xB9)
			break;
		rc = imvp_write_data();
		if (rc)
			return rc;
	}
	if (val != 0xB9) {
		CPRINTS("IMVP fault 5: CRC0 not set after 4 retries");
		return EC_ERROR_UNKNOWN;
	}

	for (retry = 0; retry < 4; retry++) {
		imvp_write(0xEF, 0x08);
		rv = imvp_read(0x0A, &val);
		if (rv)
			return rv;

		if (val == 0x82)
			break;
		rc = imvp_write_data();
		if (rc)
			return rc;
	}
	if (val != 0x82) {
		CPRINTS("IMVP fault 5: CRC1 not set after 4 retries");
		return EC_ERROR_UNKNOWN;
	}

	for (retry = 0; retry < 4; retry++) {
		imvp_write(0xEF, 0x0E);
		rv = imvp_read(0x0F, &val);
		if (rv)
			return rv;

		if (val == 0xBB)
			break;
		rc = imvp_write_data();
		if (rc)
			return rc;
	}
	if (val != 0xBB) {
		CPRINTS("IMVP fault 5: CRC1 not set after 4 retries");
		return EC_ERROR_UNKNOWN;
	}

	/*Read Test*/
	for (i = 0; i < ARRAY_SIZE(imvp_fw_write_data); i++)
		imvp_write(imvp_fw_write_data[i].reg,
			   imvp_fw_write_data[i].data);

	/*Lock NVM*/
	imvp_write(0xF1, 0xFF);

	CPRINTF("Programming Done!");
	return EC_SUCCESS;
}
