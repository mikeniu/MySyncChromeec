ZTEST(fpsensor_crypto, test_aes_128_gcm_encrypt_in_place)
{
	std::array<uint8_t, 16> plaintext{};
	std::array<uint8_t, FP_CONTEXT_TAG_BYTES> tag{};

	zassert_true(aes_128_gcm_encrypt(kTestAesKey, plaintext, plaintext,
					 kTestAesNonce, tag)
			     .has_value());
	zassert_true(plaintext == kTestAesCiphertext);
	zassert_true(tag == kTestAesTag);
}

ZTEST(fpsensor_crypto, test_aes_128_gcm_decrypt_in_place)
{
	/* Using the same values as from test_aes_gcm_encrypt_in_place means we
	 * should get back the original plaintext from that function.
	 */
	constexpr std::array<uint8_t, 16> expected_plaintext{};
	std::array<uint8_t, 16> ciphertext = kTestAesCiphertext;

	zassert_true(aes_128_gcm_decrypt(kTestAesKey, ciphertext, ciphertext,
					 kTestAesNonce, kTestAesTag)
			     .has_value());
	zassert_true(ciphertext == expected_plaintext);
}

