"""

Extract @funcprops documentation annotations from Zephyr and ChromeOS EC source trees into JSON DB.

Supports:
  1. Fast Regex Scraper (default): Scans .h and .c files in platform/ec and zephyrproject/zephyr.
  2. Optional Doxygen XML Parser (--doxygen-xml): Parses structured XML output generated by Doxygen.
"""

import argparse
import json
import os
import re
import xml.etree.ElementTree as ET


# Single Source of Truth for Supported Qualifiers
RAW_QUALIFIERS = [
    "isr_ok",
    "pre_kernel_ok",
    "sleep",
    "no_wait",
    "async",
    "supervisor",
    "reschedule",
]

# Canonical normalized qualifier set (handles both '_' and '-' variants)
QUALIFIERS = {q.replace("-", "_") for q in RAW_QUALIFIERS} | {
    q.replace("_", "-") for q in RAW_QUALIFIERS
}
NORMALIZED_QUALIFIERS = {q.replace("-", "_") for q in QUALIFIERS}

FILTER_KEYWORDS = ["funcprops", "sleep", "isr_ok", "pre_kernel_ok"]

BLOCK_PATTERN = re.compile(
    r"/\*\*([\s\S]*?)\*/\s*"
    r"(?:#[^\n]*\n\s*)*"
    r"(?:[A-Za-z0-9_]+\s+)*([A-Za-z0-9_]+)\s*\([^;\{]*\)\s*(?:;|\{)",
    re.MULTILINE,
)

INIT_MACRO_PATTERN = re.compile(
    r"(?:SYS_INIT|DEVICE_DT_DEFINE|DEVICE_DT_INST_DEFINE|DECLARE_HOOK)\s*\(\s*([A-Za-z0-9_]+)",
    re.MULTILINE,
)


def extract_qualifiers_from_text(text):
    """DRY Helper: Extract and normalize @funcprops qualifiers from Doxygen comments."""
    found = set()

    # Check explicit Doxygen @funcprops tags or \qualifier
    clean_text = text.replace("\\", " ").replace("@", " ").replace(",", " ")
    tokens = clean_text.split()

    for token in tokens:
        norm = token.replace("-", "_").strip()
        if norm in NORMALIZED_QUALIFIERS:
            found.add(norm)

    # Infer 'sleep' qualifier if Doxygen description explicitly mentions thread sleeping
    if "sleep" in text.lower() and "no sleep" not in text.lower():
        if (
            "to sleep" in text.lower()
            or "thread to sleep" in text.lower()
            or "funcprops sleep" in text.lower()
            or "sleeps" in text.lower()
        ):
            found.add("sleep")

    return sorted(list(found))


def get_default_paths():
    """Auto-detect workspace root directories relative to this script."""
    script_dir = os.path.dirname(os.path.abspath(__file__))
    ec_root = os.path.abspath(os.path.join(script_dir, "../.."))
    workspace_root = os.path.abspath(os.path.join(ec_root, "../../.."))
    zephyr_root = os.path.join(
        workspace_root, "src/third_party/zephyrproject/zephyr"
    )
    return [ec_root, zephyr_root]


def parse_doxygen_xml(xml_dir):
    """Parse Doxygen XML output files for @funcprops annotations."""
    funcprops_db = {}
    index_path = os.path.join(xml_dir, "index.xml")

    if not os.path.exists(index_path):
        print(f"[ERROR] Doxygen index.xml not found at: {index_path}")
        return funcprops_db

    print(f"Parsing Doxygen XML output from: {xml_dir}")
    tree = ET.parse(index_path)
    root = tree.getroot()

    for compound in root.findall(".//member[@kind='function']"):
        func_name = compound.findtext("name")
        ref_id = compound.get("refid")

        if func_name and ref_id:
            xml_file = os.path.join(xml_dir, f"{ref_id.split('_1')[0]}.xml")
            if os.path.exists(xml_file):
                try:
                    xml_tree = ET.parse(xml_file)
                    func_node = xml_tree.find(f".//memberdef[@id='{ref_id}']")
                    if func_node is not None:
                        dox_text = "".join(func_node.itertext())
                        props = extract_qualifiers_from_text(dox_text)
                        if props:
                            funcprops_db[func_name] = {
                                "props": props,
                                "file": xml_file,
                            }
                except Exception:
                    pass

    return funcprops_db


def scan_headers_and_sources(search_paths, output_json):
    """Fast regex scraper parsing Doxygen blocks directly preceding declarations/definitions."""
    funcprops_db = {}
    file_map = {}
    files_to_scan = []

    for root_dir in search_paths:
        if not os.path.exists(root_dir):
            print(f"[WARNING] Search path does not exist: {root_dir}")
            continue
        for root, dirs, files in os.walk(root_dir):
            dirs[:] = [
                d
                for d in dirs
                if not any(
                    d.startswith(ex)
                    for ex in ["twister-out", "build", ".git", "out"]
                )
            ]
            for file in files:
                if file.endswith(".h") or file.endswith(".c"):
                    files_to_scan.append(os.path.join(root, file))

    for file_path in files_to_scan:
        try:
            with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
                content = f.read()

            matches = BLOCK_PATTERN.findall(content)

            for comment, func_name in matches:
                props = extract_qualifiers_from_text(comment)
                if props:
                    funcprops_db[func_name] = {
                        "props": props,
                        "file": file_path,
                    }
                if file_path not in file_map.setdefault(func_name, []):
                    file_map[func_name].append(file_path)

            macro_matches = INIT_MACRO_PATTERN.findall(content)
            for func_name in macro_matches:
                if file_path not in file_map.setdefault(func_name, []):
                    file_map[func_name].append(file_path)
        except Exception:
            pass

    funcprops_db["_file_map"] = file_map

    output_dir = os.path.dirname(os.path.abspath(output_json))
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)

    with open(output_json, "w", encoding="utf-8") as f:
        json.dump(funcprops_db, f, indent=2)

    print(
        f"Extracted {len(funcprops_db)} annotated functions across {len(files_to_scan)} scanned files."
    )
    print(f"Database saved to: {output_json}")


def main():
    default_search_paths = get_default_paths()
    script_dir = os.path.dirname(os.path.abspath(__file__))
    default_output = os.path.join(script_dir, "funcprops.json")

    parser = argparse.ArgumentParser(
        description="Extract @funcprops annotations into JSON database."
    )
    parser.add_argument(
        "--search-paths",
        nargs="+",
        default=default_search_paths,
        help=f"Source/header directories to scan. Default: {default_search_paths}",
    )
    parser.add_argument(
        "--doxygen-xml",
        help="Path to generated Doxygen XML directory (optional alternative parser).",
    )
    parser.add_argument(
        "--output",
        default=default_output,
        help=f"Output JSON database file path. Default: {default_output}",
    )

    args = parser.parse_args()

    if args.doxygen_xml:
        db = parse_doxygen_xml(args.doxygen_xml)
        with open(args.output, "w", encoding="utf-8") as f:
            json.dump(db, f, indent=2)
        print(f"Saved {len(db)} functions from Doxygen XML to: {args.output}")
    else:
        scan_headers_and_sources(args.search_paths, args.output)


if __name__ == "__main__":
    main()
